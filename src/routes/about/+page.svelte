<h1>ひかいどについて</h1>
<section class="card">
  <p>
    ひかいど（HIKAIDO）は、FF14の遊び方や好みを2択にして仲間と楽しむ、無料の非公式ファンサービスです。
  </p>
  <p>
    「理解度」は、クイズを作った本人の答えと、どれくらい同じだったかを表しています。タイプ診断も理解度も、仲間と楽しむためのもの。性格や仲のよさを測るテストではないので、気軽に遊んでね。
  </p>
  <p>
    クイズは、URLを知っている人なら誰でも遊べます。パスワードで守られたページではありません。答えた人の名前・正解数・理解度・答えた日時は、誰でも見られる回答者一覧に載るので、公開してもよい名前で参加してね。
  </p>
  <p>
    作ったクイズを削除したり、答えた結果を見たりするための情報は、使ったブラウザに保存しています。ブラウザのデータを消したり、端末をなくしたりすると、その情報は元に戻せません。あとで開くときも、同じ端末・ブラウザを使ってね。
  </p>
  <p>
    別の端末を使ったり、ブラウザのデータを消したりすると、もう一度答えられることがあります。みんなの予想や正答率は、集計に含まれる回答が増えたり減ったりすると変わります。
  </p>
